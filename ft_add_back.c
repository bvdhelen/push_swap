#include "../includes/push_swap.h"

//Función para añadir un nuevo nodo al final de un stack
void	ft_add_back(t_stack **stack, t_stack *new_node)
{
	if (!stack)
		return ;
	if (!*stack)
		*stack = new_node;
	else
		(last(*stack))->next = new_node;
}
