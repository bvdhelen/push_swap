#include "../includes/push_swap.h"

//Función para comprobar si hay números duplicados
int	check_duplicates(t_stack *stack)
{
	t_stack	*temp;

	while (stack)
	{
		temp = stack->next;
		while (temp)
		{
			if (stack->nbr == temp->nbr)
				return (1);
			temp = temp->next;
		}
		stack = stack->next;
	}
	return (0);
}
