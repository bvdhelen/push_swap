#include "../includes/push_swap.h"

//Función para encontrar y devolver el menor número en un stack
int	min(t_stack *stack)
{
	int	min;

	min = stack->nbr;
	while (stack)
	{
		if (stack->nbr < min)
			min = stack->nbr;
		stack = stack->next;
	}
	return (min);
}
