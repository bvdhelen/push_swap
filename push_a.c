#include "../includes/push_swap.h"

//Función que coge el primer elemento del stack B y lo pone 1º en el stack A
void	pa(t_stack **a, t_stack **b, int j)
{
	t_stack	*temp;

	if (!*b)
		return ;
	temp = *a;
	*a = *b;
	*b = (*b)->next;
	(*a)->next = temp;
	if (j == 0)
		write(1, "pa\n", 3);
}
