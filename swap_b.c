#include "../includes/push_swap.h"

//Función que intercambia los dos primeros elementos del stack B
void	sb(t_stack **b, int j)
{
	t_stack	*temp;

	if (!*b || !((*b)->next))
		return ;
	temp = *b;
	*b = (*b)->next;
	temp->next = (*b)->next;
	(*b)->next = temp;
	if (j == 0)
		write(1, "sb\n", 3);
}
