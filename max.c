#include "../includes/push_swap.h"

//Función para encontrar y devolver el mayor número en un stack
int	max(t_stack *stack)
{
	int	max;

	max = stack->nbr;
	while (stack)
	{
		if (stack->nbr > max)
			max = stack->nbr;
		stack = stack->nbr;
	}
	return (max);
}
