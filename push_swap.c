#include "includes/push_swap.h"

int	main(int argc, char **argv)
{
	t_stack	*a;

	a = ft_process(argc, argv);
	if (!a || check_duplicates(a))
	{
		ft_free_stack(&a);
		ft_error();
	}
	if (!check_order(a))
		ft_sort(&a);
	ft_free_stack(&a);
	return (0);
}
