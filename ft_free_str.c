#include "../includes/push_swap.h"

//Función para liberar la memoria de un string
void	free_str(char **lst)
{
	char	*str;

	if (!lst)
		return ;
	while (*lst)
	{
		str = *lst;
		lst++;
		free(str);
	}
	*lst = NULL;
}
