#include "../includes/push_swap.h"

//Función para crear un nuevo nodo con el número dado en un stack
t_stack	*new_node(int content)
{
	t_stack	*new;

	new = malloc(sizeof (t_stack));
	if (!new)
		ft_error();
	new->nbr = content;
	new->next = NULL;
	return (new);
}
