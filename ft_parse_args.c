#include "../includes/push_swap.h"

//Función para parsear los argumentos
t_stack	*ft_parse_args(int argc, char **argv)
{
	t_stack	*stack_a;
	int		i;
	int		j;

	i = 1;
	stack_a = NULL;
	if (argc < 2)
		ft_error();
	if (argc == 2)
		stack_a = fill_stack(argv);
	else
	{
		list_args(argv, &stack_a);
	}
	return (stack_a);
}
