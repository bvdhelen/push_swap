#include "../includes/push_swap.h"

int	alpha_num(int c)
{
	if ((c >= 58 && c <= 126) || (c >= 33 && c <= 42)
		|| (c == 44) || (c == 46) || (c == 47))
		return (1);
	return (0);
}

//Función para comprobar si los argumentos son carácteres alfanuméricos
void	check_alpha(char **argv)
{
	int	i;
	int	j;

	i = 1;
	while (argv[i])
	{
		j = 0;
		while ((argv[i][j]) != '\0')
		{
			if (alpha_num(argv[i][j]))
				ft_error();
			j++;
		}
		i++;
	}
}
